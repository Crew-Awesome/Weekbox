import type { HostAdapter, HostDirectoryEntry } from '@/core/host'
import type { WeekBoxLibraryPaths } from '@/core/storage/weekbox-library'
import { detectModEngineFromFiles, extractBaseModId } from './mod-filesystem'
import type { InstalledModRecord } from './types'

export interface ParsedModFolderIdentity {
  rawTitlePrefix: string
  baseModId: string | null
  compositeId: string | null
}

/**
 * Encodes a mod identifier using the exact filename sanitization scheme used by WeekBox v2.
 */
export function safeCoverFileName(modId: string | number): string {
  return encodeURIComponent(String(modId)).replaceAll('%', '_')
}

/**
 * Mirrors WeekBox v2's `sanitizePathSegment` helper for fallback folder matching.
 */
export function sanitizePathSegment(value: string | undefined | null): string {
  return String(value || '')
    .replace(/[<>:"/\\|?*]+/g, '')
    .trim()
}

/**
 * Extracts `<titlePrefix>`, `<baseModId>`, and `<compositeId>` from a mod directory name
 * created by WeekBox (`TITLE--12345--uuid`, `TITLE--12345`, or plain folder name).
 */
export function parseModFolderIdentity(folderName: string): ParsedModFolderIdentity {
  const parts = folderName.split('--')
  if (parts.length >= 3 && parts[1]) {
    const rest = parts.slice(2).join('--')
    return {
      rawTitlePrefix: parts[0] || folderName,
      baseModId: parts[1],
      compositeId: `${parts[1]}--${rest}`,
    }
  }
  if (parts.length === 2 && /^\d+$/.test(parts[1])) {
    return {
      rawTitlePrefix: parts[0] || folderName,
      baseModId: parts[1],
      compositeId: parts[1],
    }
  }
  return {
    rawTitlePrefix: folderName,
    baseModId: null,
    compositeId: null,
  }
}

export function prettifyFolderTitle(rawPrefix: string): string {
  return rawPrefix.replace(/[_]+/g, ' ').replace(/\s+/g, ' ').trim() || 'Installed Mod'
}

/**
 * Detects whether a title looks like a compacted uppercase folder prefix (`BESIMGFSKIN`)
 * so online enrichment can restore the canonical GameBanana title once connected.
 */
export function isAutoGeneratedFolderTitle(
  title: string | undefined,
  folderName: string | undefined,
): boolean {
  if (!title || !folderName) return false
  const prefix = folderName.split('--')[0] || ''
  return Boolean(prefix && title === prefix && /^[A-Z0-9]{4,}$/.test(title))
}

function getPathBasename(filePath: string | undefined): string {
  if (!filePath) return ''
  const clean = filePath.replace(/\\/g, '/').replace(/\/+$/, '')
  const idx = clean.lastIndexOf('/')
  return idx >= 0 ? clean.slice(idx + 1) : clean
}

/**
 * Normalizes a raw manifest object coming from either WeekBox v2 (`installed-mods.json`)
 * or WeekBox rew (`installedmods.json`) into a unified `InstalledModRecord`.
 */
export function normalizeV2ModRecord(raw: Partial<InstalledModRecord>): InstalledModRecord {
  const folderName =
    raw.folderName ||
    getPathBasename(raw.installPath) ||
    sanitizePathSegment(raw.name || raw.title) ||
    ''

  const parsedFolder = folderName ? parseModFolderIdentity(folderName) : null
  const resolvedHidden =
    raw.hidden !== undefined ? Boolean(raw.hidden) : raw.visible === false
  const resolvedVisible =
    raw.visible !== undefined ? Boolean(raw.visible) && !resolvedHidden : !resolvedHidden

  const rawModId =
    raw.modId ??
    raw.gameBananaId ??
    raw.providerId ??
    (parsedFolder?.baseModId && /^\d+$/.test(parsedFolder.baseModId)
      ? parsedFolder.baseModId
      : undefined)

  const idFromRecord =
    raw.id !== undefined && raw.id !== null && String(raw.id).trim() !== ''
      ? raw.id
      : parsedFolder?.compositeId || rawModId || folderName || `local-${Date.now()}`

  const resolvedTitle =
    raw.title ||
    raw.name ||
    (parsedFolder ? prettifyFolderTitle(parsedFolder.rawTitlePrefix) : 'Unnamed Mod')

  return {
    ...raw,
    id: idFromRecord,
    modId: rawModId,
    name: raw.name || resolvedTitle,
    title: resolvedTitle,
    installPath: raw.installPath || '',
    folderName,
    engineFolderName: raw.engineFolderName || sanitizePathSegment(raw.name || raw.title) || folderName,
    hidden: resolvedHidden,
    visible: resolvedVisible,
    sourceUrl: raw.sourceUrl || raw.providerUrl || raw.meta?.link,
    thumbnail: raw.thumbnail || raw.image || undefined,
    image: raw.image || raw.thumbnail || undefined,
  }
}

export function getModRecordMatchKeys(item: Partial<InstalledModRecord>): string[] {
  const keys: string[] = []
  if (item.id !== undefined && item.id !== null && String(item.id).trim()) {
    keys.push(`id:${String(item.id).trim().toLowerCase()}`)
  }
  const folder = item.folderName || getPathBasename(item.installPath)
  if (folder) {
    keys.push(`folder:${folder.trim().toLowerCase()}`)
  }
  return keys
}

/**
 * Merges a primary record (`installed-mods.json` / v2) with a secondary record
 * (`installedmods.json` / rew) so neither side loses runtime metadata or artwork.
 */
export function mergeModRecords(
  primary: InstalledModRecord,
  secondary: InstalledModRecord,
): InstalledModRecord {
  const preferName =
    primary.title && !isAutoGeneratedFolderTitle(primary.title, primary.folderName)
      ? primary.title
      : secondary.title || primary.title || secondary.name || primary.name

  return {
    ...secondary,
    ...primary,
    name: primary.name && !isAutoGeneratedFolderTitle(primary.name, primary.folderName)
      ? primary.name
      : preferName,
    title: preferName,
    folderName: primary.folderName || secondary.folderName,
    engineFolderName: primary.engineFolderName || secondary.engineFolderName,
    installPath: primary.installPath || secondary.installPath,
    description: primary.description || secondary.description,
    htmlBody: primary.htmlBody || secondary.htmlBody,
    author: primary.author || secondary.author,
    userPfp: primary.userPfp || secondary.userPfp,
    userPfpPath: primary.userPfpPath || secondary.userPfpPath,
    localUserPfp: primary.localUserPfp || secondary.localUserPfp,
    authors:
      primary.authors && primary.authors.length > 0
        ? primary.authors
        : secondary.authors,
    credits:
      primary.credits && primary.credits.length > 0
        ? primary.credits
        : secondary.credits,
    thumbnail: primary.thumbnail || secondary.thumbnail,
    image: primary.image || secondary.image,
    previewMedia:
      primary.previewMedia && primary.previewMedia.length > 0
        ? primary.previewMedia
        : secondary.previewMedia,
    coverPath: primary.coverPath || secondary.coverPath,
    localCoverPath: primary.localCoverPath || secondary.localCoverPath,
    installedAt: primary.installedAt ?? secondary.installedAt,
    lastPlayedAt: primary.lastPlayedAt ?? secondary.lastPlayedAt,
    tags: primary.tags && primary.tags.length > 0 ? primary.tags : secondary.tags,
    views: primary.views ?? secondary.views,
    likes: primary.likes ?? secondary.likes,
    downloads: primary.downloads ?? secondary.downloads,
    meta: {
      ...secondary.meta,
      ...primary.meta,
    },
  }
}

export async function resolveDiskModPath(
  host: HostAdapter,
  item: InstalledModRecord,
  modsDir: string,
  diskDirsByLower: Map<string, HostDirectoryEntry>,
): Promise<{ installPath: string; folderName: string }> {
  const folderCandidates = [
    item.folderName,
    getPathBasename(item.installPath),
    sanitizePathSegment(item.name),
    sanitizePathSegment(item.title),
  ].filter(Boolean) as string[]

  for (const candidate of folderCandidates) {
    const matched = diskDirsByLower.get(candidate.toLowerCase())
    if (matched) {
      return { installPath: matched.path, folderName: matched.name }
    }
  }

  if (item.installPath) {
    if (await host.fs.exists(item.installPath)) {
      return {
        installPath: item.installPath,
        folderName: item.folderName || getPathBasename(item.installPath),
      }
    }
  }

  return {
    installPath: item.installPath || '',
    folderName: item.folderName || '',
  }
}

/**
 * Checks whether a mod directory contains at least one non-temporary file.
 */
export async function hasDirectoryContent(
  host: HostAdapter,
  dirPath: string,
  depth = 0,
  preloadedEntries?: HostDirectoryEntry[],
): Promise<boolean> {
  if (depth > 2) return false
  try {
    const entries = preloadedEntries ?? (await host.fs.readDirectory(dirPath))
    const subDirs: string[] = []
    for (const entry of entries) {
      if (entry.name === '.' || entry.name === '..' || entry.name === '.downloading') {
        continue
      }
      if (!entry.isDirectory) return true
      subDirs.push(entry.path)
    }
    if (depth < 2 && subDirs.length > 0) {
      const nested = await Promise.all(
        subDirs.slice(0, 6).map((sub) => hasDirectoryContent(host, sub, depth + 1)),
      )
      return nested.some(Boolean)
    }
  } catch {
  }
  return false
}

export async function resolveOnDiskCover(
  host: HostAdapter,
  paths: WeekBoxLibraryPaths,
  candidateIds: Array<string | number | undefined | null>,
  cachedFilesByLower?: Map<string, HostDirectoryEntry>,
): Promise<{ coverPath?: string; localCoverPath?: string }> {
  const uniqueIds = Array.from(
    new Set(
      candidateIds
        .map((v) => (v !== undefined && v !== null ? String(v).trim() : ''))
        .filter(Boolean),
    ),
  )

  const fileNames: string[] = []
  for (const id of uniqueIds) {
    const safeId = safeCoverFileName(id)
    const baseId = extractBaseModId(id)
    for (const ext of ['webp', 'png', 'jpg']) {
      fileNames.push(`${id}.${ext}`)
      if (safeId !== id) fileNames.push(`${safeId}.${ext}`)
      if (baseId && baseId !== id) {
        fileNames.push(`${baseId}.${ext}`)
        fileNames.push(`mod_${baseId}.${ext}`)
      }
    }
  }

  let lookupMap = cachedFilesByLower
  if (!lookupMap) {
    try {
      const entries = await host.fs.readDirectory(paths.modCoversDir)
      lookupMap = new Map<string, HostDirectoryEntry>()
      for (const e of entries) {
        if (!e.isDirectory) lookupMap.set(e.name.toLowerCase(), e)
      }
    } catch {
      lookupMap = new Map()
    }
  }

  for (const fileName of fileNames) {
    const match = lookupMap.get(fileName.toLowerCase())
    if (match) {
      return {
        coverPath: `mod-covers/${match.name}`,
        localCoverPath: match.path,
      }
    }
  }

  return {}
}

export async function resolveOnDiskSubmitterAvatar(
  host: HostAdapter,
  paths: WeekBoxLibraryPaths,
  baseModId: string | null | undefined,
  cachedFilesByLower?: Map<string, HostDirectoryEntry>,
): Promise<{ userPfpPath?: string; localUserPfp?: string }> {
  if (!baseModId) return {}

  let lookupMap = cachedFilesByLower
  if (!lookupMap) {
    try {
      const entries = await host.fs.readDirectory(paths.modAvatarsDir)
      lookupMap = new Map<string, HostDirectoryEntry>()
      for (const e of entries) {
        if (!e.isDirectory) lookupMap.set(e.name.toLowerCase(), e)
      }
    } catch {
      lookupMap = new Map()
    }
  }

  for (const ext of ['png', 'jpg', 'jpeg', 'webp', 'gif']) {
    const fileName = `${baseModId}--submitter.${ext}`
    const match = lookupMap.get(fileName.toLowerCase())
    if (match) {
      return {
        userPfpPath: `mod-avatars/${match.name}`,
        localUserPfp: match.path,
      }
    }
  }
  return {}
}

async function readJsonFromPreloadedEntries<T>(
  host: HostAdapter,
  rootEntriesByLower: Map<string, HostDirectoryEntry>,
  fileName: string,
): Promise<T | null> {
  const entry = rootEntriesByLower.get(fileName.toLowerCase())
  if (!entry || entry.isDirectory) return null
  try {
    const raw = await host.fs.readTextFile(entry.path)
    if (!raw || !raw.trim()) return null
    return JSON.parse(raw) as T
  } catch {
    return null
  }
}

async function readGameBananaUrlIdFromEntries(
  host: HostAdapter,
  rootEntriesByLower: Map<string, HostDirectoryEntry>,
): Promise<{ modId?: string; url?: string }> {
  for (const fileName of ['mod_url.txt', 'link.txt']) {
    const entry = rootEntriesByLower.get(fileName)
    if (!entry || entry.isDirectory) continue
    try {
      const content = (await host.fs.readTextFile(entry.path)).trim()
      if (!content) continue
      const match = content.match(/gamebanana\.com\/mods\/(\d+)/i)
      return {
        modId: match?.[1],
        url: content.startsWith('http') ? content : undefined,
      }
    } catch {
    }
  }
  return {}
}

function stableFolderId(folderName: string): string {
  let hash = 5381
  for (const ch of folderName) {
    hash = ((hash * 33) ^ ch.charCodeAt(0)) >>> 0
  }
  return `local-${hash.toString(36)}`
}

/**
 * Inspects an unregistered directory inside `WeekBoxLibrary/mods/` using a single
 * root directory listing and cached cover/avatar lookup maps.
 */
export async function discoverUnregisteredModDirectory(
  host: HostAdapter,
  entry: HostDirectoryEntry,
  paths: WeekBoxLibraryPaths,
  coversByLower?: Map<string, HostDirectoryEntry>,
  avatarsByLower?: Map<string, HostDirectoryEntry>,
): Promise<InstalledModRecord | null> {
  if (!entry.isDirectory || entry.name.startsWith('.')) return null

  const rootEntries = await host.fs.readDirectory(entry.path)
  if (!rootEntries || rootEntries.length === 0) return null

  const rootEntriesByLower = new Map<string, HostDirectoryEntry>()
  for (const item of rootEntries) {
    rootEntriesByLower.set(item.name.toLowerCase(), item)
  }

  if (rootEntriesByLower.has('.downloading')) return null
  if (!(await hasDirectoryContent(host, entry.path, 0, rootEntries))) return null

  const [legacyModJson, polymodMeta, packJson, urlMeta] = await Promise.all([
    readJsonFromPreloadedEntries<Partial<InstalledModRecord>>(
      host,
      rootEntriesByLower,
      'mod.json',
    ),
    readJsonFromPreloadedEntries<{
      title?: string
      description?: string
      contributors?: Array<{ name?: string }>
    }>(host, rootEntriesByLower, '_polymod_meta.json'),
    readJsonFromPreloadedEntries<{
      name?: string
      description?: string
    }>(host, rootEntriesByLower, 'pack.json'),
    readGameBananaUrlIdFromEntries(host, rootEntriesByLower),
  ])

  const parsed = parseModFolderIdentity(entry.name)
  const inferredBaseId =
    parsed.baseModId ||
    urlMeta.modId ||
    (legacyModJson?.modId ? String(legacyModJson.modId) : null)

  const id =
    legacyModJson?.id ||
    parsed.compositeId ||
    inferredBaseId ||
    stableFolderId(entry.name)

  const fallbackEngine =
    legacyModJson?.engineId ||
    (polymodMeta ? 'vslice' : packJson ? 'psych' : undefined)

  const detected = await detectModEngineFromFiles(entry.path, fallbackEngine)
  const [coverInfo, avatarInfo] = await Promise.all([
    resolveOnDiskCover(host, paths, [id, inferredBaseId, entry.name], coversByLower),
    resolveOnDiskSubmitterAvatar(host, paths, inferredBaseId, avatarsByLower),
  ])

  const displayName =
    legacyModJson?.title ||
    legacyModJson?.name ||
    polymodMeta?.title?.trim() ||
    packJson?.name?.trim() ||
    prettifyFolderTitle(parsed.rawTitlePrefix)

  const description =
    legacyModJson?.description ||
    polymodMeta?.description ||
    packJson?.description ||
    undefined

  const inferredAuthor =
    legacyModJson?.author ||
    polymodMeta?.contributors?.find((c) => c.name)?.name ||
    undefined

  const numericModId =
    inferredBaseId && /^\d+$/.test(inferredBaseId) ? Number(inferredBaseId) : undefined

  return normalizeV2ModRecord({
    ...legacyModJson,
    id,
    modId: numericModId ?? legacyModJson?.modId ?? inferredBaseId ?? undefined,
    name: legacyModJson?.name || displayName,
    title: displayName,
    description,
    author: inferredAuthor,
    engineId: detected.engineId,
    isExecutable: detected.isExecutable,
    hasEngineWarning: detected.hasEngineWarning,
    engineWarningMessage: detected.engineWarningMessage,
    installPath: entry.path,
    folderName: entry.name,
    engineFolderName: legacyModJson?.engineFolderName || entry.name,
    source: numericModId ? 'gamebanana' : legacyModJson?.source || 'local',
    sourceUrl:
      legacyModJson?.sourceUrl ||
      urlMeta.url ||
      (numericModId ? `https://gamebanana.com/mods/${numericModId}` : undefined),
    coverPath: legacyModJson?.coverPath || coverInfo.coverPath,
    localCoverPath: legacyModJson?.localCoverPath || coverInfo.localCoverPath,
    userPfpPath: legacyModJson?.userPfpPath || avatarInfo.userPfpPath,
    localUserPfp: legacyModJson?.localUserPfp || avatarInfo.localUserPfp,
    installedAt: legacyModJson?.installedAt ?? Date.now(),
  })
}
